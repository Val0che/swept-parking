// Bundles the core into one script and embeds it in a Swift source file, so the
// native intents run exactly the code the tests cover.
// Run: pnpm --filter @swept/core bundle:native
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const out = new URL('../../app/native/SweptCoreBundle.swift', import.meta.url);
const result = await build({
  entryPoints: [new URL('../src/native.ts', import.meta.url).pathname],
  bundle: true,
  format: 'iife',
  globalName: 'SweptCore',
  target: 'es2020',
  minify: true,
  write: false,
});
const js = result.outputFiles[0].text;
if (js.includes('"""##')) throw new Error('bundle contains the Swift raw-string terminator');

writeFileSync(
  out,
  `// GENERATED by core/scripts/bundle-native.mjs — do not edit.
// The @swept/core logic (side lookup, schedule, notification plan) as JavaScript.

enum SweptCoreBundle {
  static let source = ##"""
${js}
"""##
}
`,
);
console.log(`SweptCoreBundle.swift: ${(js.length / 1024).toFixed(1)} KB of JavaScript`);
